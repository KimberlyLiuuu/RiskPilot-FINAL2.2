# -*- coding: utf-8 -*-
"""
RiskPilot Baseline display layer (Streamlit-free).

This module owns two things that must be testable without a Streamlit
runtime:

1. The **deterministic legacy translation** of the closed set of baseline
   sentences produced by the built-in rules (``risk_chains`` / ``impacts`` /
   ``actions``). Display-only: nothing is ever written back to project data.

2. The **per-language content selection** for the Baseline view. The single
   entry point is :func:`get_baseline_display_text`, which decides what the
   current interface language may safely display.

Hard rules enforced here:

* A project never mixes two languages in one section. When an archive for
  the current language exists, only that archive is read.
* A missing current-language archive never falls back to another language's
  *free text*. Only text that belongs to the known deterministic template
  set is translated locally; unknown text is hidden instead of being shown
  in the wrong language.
* :func:`get_baseline_display_text` is read-only: it does not mutate the
  project, does not call ``persist()``, does not touch ``st.session_state``,
  does not read ``ui_lang`` and never calls the AI. Generating a new
  language version stays an explicit, user-triggered page action.
* Risk values (``score`` / ``level`` / ``risks`` / ``selected_hazards`` and
  the S x L x E inputs) are never read or written by this module.
"""

